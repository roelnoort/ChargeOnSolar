#!/usr/bin/env bash
#
# Runs shellcheck on every shell script git tracks: files ending in .sh or
# .bash, and files whose first line is a sh/bash/dash/ksh shebang. New scripts
# are picked up without editing this file or the CI config.
#
# To silence a finding, disable it on the line with a comment that says why:
#   # Reason the check doesn't apply here.
#   # shellcheck disable=SC1234

set -euo pipefail

if ! command -v shellcheck >/dev/null 2>&1; then
  echo "shellcheck is not installed. Install it with 'brew install shellcheck' (macOS) or 'apt install shellcheck' (Ubuntu)." >&2
  exit 1
fi

cd "$(git rev-parse --show-toplevel)"

scripts=()
while IFS= read -r -d '' file; do
  [[ -f "$file" ]] || continue
  case "$file" in
    *.sh | *.bash) scripts+=("$file") ;;
    *)
      first_line=$(head -n 1 "$file" 2>/dev/null || true)
      if [[ "$first_line" =~ ^#!.*(/|[[:space:]])(ba|da|k)?sh([[:space:]]|$) ]]; then
        scripts+=("$file")
      fi
      ;;
  esac
done < <(git ls-files -z)

if ((${#scripts[@]} == 0)); then
  echo "No shell scripts found."
  exit 0
fi

# Wizards carry the /wizard skill's library verbatim, and it must not be
# hand-edited. Two findings in that library are excused for wizards only:
#   SC2329: each wizard leaves some library functions unused.
#   SC1087: `$e[Enter keeps current]` reads like an array index, but `$e` is a
#           plain string (a Readline marker) followed by literal text.
wizards=()
others=()
for file in "${scripts[@]}"; do
  if grep -q '^# Generated by the /wizard skill\.$' "$file"; then
    wizards+=("$file")
  else
    others+=("$file")
  fi
done

echo "shellcheck $(shellcheck --version | sed -n 's/^version: //p') on ${#scripts[@]} scripts:"
printf '  %s\n' "${scripts[@]}"
status=0
if ((${#others[@]} > 0)); then
  shellcheck "${others[@]}" || status=1
fi
if ((${#wizards[@]} > 0)); then
  shellcheck --exclude=SC2329,SC1087 "${wizards[@]}" || status=1
fi
if ((status == 0)); then echo "No findings."; fi
exit "$status"
